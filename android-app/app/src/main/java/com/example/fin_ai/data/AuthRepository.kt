package com.example.fin_ai.data

import android.content.Context
import androidx.credentials.CredentialManager
import androidx.credentials.GetCredentialRequest
import com.example.fin_ai.R
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.FirebaseUser
import com.google.firebase.auth.GoogleAuthProvider
import kotlinx.coroutines.tasks.await

class AuthRepository(private val auth: FirebaseAuth = FirebaseAuth.getInstance()) {

    val currentUser: FirebaseUser? get() = auth.currentUser

    suspend fun signInWithEmail(email: String, password: String): FirebaseUser {
        val result = auth.signInWithEmailAndPassword(email, password).await()
        val user = requireNotNull(result.user) { "Sign-in returned no user" }
        syncToBackend(user, provider = "email")
        return user
    }

    suspend fun signInWithGoogle(context: Context): FirebaseUser {
        // default_web_client_id is generated by the google-services plugin from
        // google-services.json — it is the OAuth *web* client, which is what
        // Firebase requires to exchange a Google ID token.
        val option = GetSignInWithGoogleOption.Builder(
            context.getString(R.string.default_web_client_id)
        ).build()

        val response = CredentialManager.create(context).getCredential(
            context,
            GetCredentialRequest.Builder().addCredentialOption(option).build()
        )

        val googleIdToken = GoogleIdTokenCredential
            .createFrom(response.credential.data)
            .idToken

        val result = auth
            .signInWithCredential(GoogleAuthProvider.getCredential(googleIdToken, null))
            .await()
        val user = requireNotNull(result.user) { "Google sign-in returned no user" }
        syncToBackend(user, provider = "google")
        return user
    }

    fun signOut() = auth.signOut()

    /** Mirrors the web app: upsert the profile into MongoDB after a successful login. */
    private suspend fun syncToBackend(user: FirebaseUser, provider: String) {
        runCatching {
            ApiClient.api.syncUser(
                SyncUserRequest(
                    uid = user.uid,
                    name = user.displayName.orEmpty(),
                    email = user.email.orEmpty(),
                    phone = user.phoneNumber.orEmpty(),
                    provider = provider,
                )
            )
        }
    }
}
